class TestAttributionPattern(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.grep = _grep()
        if not cls.grep:
            raise unittest.SkipTest("grep not found on PATH or beside git")
        # From a file, as UTF-8 bytes: a non-ASCII pattern passed as an
        # argument is re-encoded on the way to a Windows grep.
        cls.work = tempfile.TemporaryDirectory()
        cls.pattern_file = Path(cls.work.name) / "pattern.txt"
        cls.pattern_file.write_bytes(_pattern().encode("utf-8") + b"\n")

    @classmethod
    def tearDownClass(cls):
        cls.work.cleanup()

    def _matches(self, line, locale):
        # The workflow runs grep in a UTF-8 locale and a hook may run in
        # C: the Unicode hyphens are written as alternatives, not in a
        # bracket expression, so they match as whole byte sequences in both.
        r = subprocess.run([self.grep, "-Ei", "-f", str(self.pattern_file)],
                           input=(line + "\n").encode("utf-8"),
                           capture_output=True, env={**os.environ, "LC_ALL": locale})
        self.assertIn(r.returncode, (0, 1), r.stderr.decode("utf-8", "replace"))
        return r.returncode == 0

    def test_attribution_lines_match(self):
        for locale in ("C.UTF-8", "C"):
            for label, line in MUST_MATCH:
                with self.subTest(label, locale=locale):
                    self.assertTrue(self._matches(line, locale), "not caught")

    def test_ordinary_text_does_not_match(self):
        for locale in ("C.UTF-8", "C"):
            for label, line in MUST_NOT_MATCH:
                with self.subTest(label, locale=locale):
                    self.assertFalse(self._matches(line, locale), "refused")


if __name__ == "__main__":
    unittest.main()
