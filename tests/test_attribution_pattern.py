"""
Tests the pattern .github/workflows/attribution.yml looks for.

WHY
───
The workflow fails a push, a pull request or a release whose text
carries an attribution line. Its pattern is the local hooks' pattern,
character for character, and is easy to get subtly wrong in either
direction: forms of a trailer it lets through (another trailer name,
the co-author trailer typed with a Unicode hyphen, a chat link with a
path nobody listed), or ordinary prose it refuses ("helped by
caching", a tool's name as the start of a longer word). This runs
the pattern the way the workflow does, with `grep -Ei`, over lines
that must match (a sample for every branch) and lines that must not.

The samples are assembled from pieces, so that no attribution line is
written out in this file: a search of the repository with the pattern
stays clean, and so does the diff `git commit -v` shows.

Needs grep: on PATH, or the one Git for Windows ships.
"""

import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).parent.parent
WORKFLOW = ROOT / ".github" / "workflows" / "attribution.yml"

HYPHENS = {"ASCII": "-", "U+2010": "‐", "U+2011": "‑"}


def _pattern():
    found = re.findall(r"^\s*pattern='(.*)'$", WORKFLOW.read_text(encoding="utf-8"), re.M)
    assert len(found) == 1, f"expected one pattern in {WORKFLOW.name}, found {len(found)}"
    return found[0]


def _grep():
    found = shutil.which("grep")
    if found:
        return found
    # Git for Windows keeps its grep out of PATH: usr/bin, next to the
    # mingw64 folder that holds git's own programs.
    try:
        exec_path = subprocess.run(["git", "--exec-path"], capture_output=True,
                                   text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None
    candidate = Path(exec_path).parents[2] / "usr" / "bin" / "grep.exe"
    return str(candidate) if candidate.is_file() else None


def _trailer(name, hyphen="-", colon=":", who="A <a@example.com>"):
    """`name` as a trailer line, its words joined by `hyphen`."""
    return hyphen.join(name.split()) + colon + " " + who


def _says(verb, rest):
    """`verb` and `rest` as one line ("Generated with X")."""
    return verb + " " + rest


